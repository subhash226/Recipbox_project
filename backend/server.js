import "dotenv/config";
import express from "express";
import cors from "cors";
import rateLimit from "express-rate-limit";
import connectDB from "./config/db.js";
import authRoutes from "./routes/authRoutes.js";
import recipeRoutes from "./routes/recipeRoutes.js";
import userRoutes from "./routes/userRoutes.js";
import notificationRoutes from "./routes/notificationRoutes.js";
import reportRoutes from "./routes/reportRoutes.js";
import uploadRoutes from "./routes/uploadRoutes.js";

if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) throw new Error("Set JWT_SECRET to a random secret with at least 32 characters.");
await connectDB();
const app=express();app.disable("x-powered-by");app.use(cors({origin:process.env.CLIENT_ORIGIN||"http://localhost:5173"}));app.use(express.json({limit:"1mb"}));
app.get("/api/health",(_req,res)=>res.json({status:"ok"}));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use("/api/recipes",recipeRoutes);app.use("/api/users",userRoutes);app.use("/api/notifications",notificationRoutes);app.use("/api/reports",reportRoutes);
app.use("/api/uploads",uploadRoutes);
app.use((req,res)=>res.status(404).json({message:"API route not found."}));
app.use((err,_req,res,_next)=>{console.error(err);if(err.code===11000)return res.status(409).json({message:"An account with this email already exists."});if(err.name==="ValidationError")return res.status(400).json({message:err.message});res.status(500).json({message:"Something went wrong. Please try again."});});
const port=Number(process.env.PORT)||5000;app.listen(port,()=>console.log(`RecipeBox API listening on port ${port}`));
